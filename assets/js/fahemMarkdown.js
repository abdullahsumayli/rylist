/* ==========================================================================
   تحويل ردّ فاهم إلى HTML آمن.

   النموذج يكتب ماركداون (خط عريض لأسماء المشاريع تحديدًا). الفقاعة كانت تهرّب
   النص كاملاً فيرى المستخدم `**نجد ٥**` بالنجمات. هنا نهرّب أولاً ثم نحوّل،
   بهذا الترتيب: أي HTML في ردّ النموذج يصير نصًّا ميتًا قبل أن نضيف وسومنا،
   فلا مجال لحقن HTML عبر الردّ.
   ========================================================================== */

export function esc(s) {
  return String(s == null ? "" : s).replace(
    /[&<>"]/g,
    (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c])
  );
}

export function renderMessage(s) {
  // [^*\n]+ يمنع المطابقة عبر سطرين ويمنع `****` الفارغة من إنتاج وسم فارغ.
  return esc(s).replace(/\*\*([^*\n]+)\*\*/g, "<strong>$1</strong>");
}
