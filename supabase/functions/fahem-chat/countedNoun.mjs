/* ==========================================================================
   صياغة جملة "لقيت لك N مشاريع" بعدد سليم في كل لغة.

   العربية تعدّ بثلاث صيغ لا صيغة واحدة، والفعل يتبعها:
     ١  → مفرد،  «مشروعًا يناسب»
     ٢  → مثنّى، «مشروعين يناسبان»
     ٣-١٠ → عدد مكتوب + جمع، «ثلاثة مشاريع تناسب»
   و«مشروع» مذكّر، فعدده من ٣ إلى ١٠ يُؤنَّث (ثلاثة لا ثلاث). وما بعد العشرة
   تمييزه مفرد منصوب: «اثنا عشر مشروعًا».

   الرقم الغربي داخل النص العربي كان يظهر لأن الصيغة القديمة كانت قالبًا واحدًا
   لكل الأعداد: `هذي ${n} مشاريع` → «هذي 2 مشاريع».

   والصينية تستبدل 二 بـ 两 قبل المصنّف، فـ«2 个项目» ركيكة والصحيح «两个项目».
   ========================================================================== */

// أسماء الأعداد المؤنّثة (لمعدود مذكّر) من ٣ إلى ١٠.
const AR_ONES = { 3: "ثلاثة", 4: "أربعة", 5: "خمسة", 6: "ستة", 7: "سبعة", 8: "ثمانية", 9: "تسعة", 10: "عشرة" };

// الأرقام الهندية المستخدمة في نصوص الموقع العربية.
const AR_DIGITS = "٠١٢٣٤٥٦٧٨٩";
const toArabicDigits = (n) => String(n).replace(/[0-9]/g, (d) => AR_DIGITS[+d]);

function arabicLine(n, city) {
  if (n === 1) return `أبشر! لقيت لك مشروعًا يناسب طلبك في ${city}:`;
  if (n === 2) return `أبشر! لقيت لك مشروعين يناسبان طلبك في ${city}:`;
  if (AR_ONES[n]) return `أبشر! لقيت لك ${AR_ONES[n]} مشاريع تناسب طلبك في ${city}:`;
  // ما بعد العشرة: تمييز مفرد منصوب، والرقم بالأرقام الهندية لا الغربية.
  return `أبشر! لقيت لك ${toArabicDigits(n)} مشروعًا تناسب طلبك في ${city}:`;
}

function chineseLine(n, city) {
  if (n === 1) return `好的！我在${city}为您找到一个符合需求的项目：`;
  if (n === 2) return `好的！这是${city}符合您需求的两个项目：`;
  return `好的！这是${city}符合您需求的 ${n} 个项目：`;
}

function englishLine(n, city) {
  return `Here ${n > 1 ? "are" : "is"} ${n} matching project${n > 1 ? "s" : ""} in ${city}:`;
}

export function foundLine(n, city, lang) {
  if (lang === "ar") return arabicLine(n, city);
  if (lang === "zh") return chineseLine(n, city);
  return englishLine(n, city);
}
